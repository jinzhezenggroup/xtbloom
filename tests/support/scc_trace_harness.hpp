std::vector<std::vector<double>> TraceBatch::live_state(std::int64_t system) const {
  const Geometry& g = *geometry_;
  const std::int64_t shell_begin = g.layout.qsh.system_offsets[system];
  const std::int64_t shell_end = g.layout.qsh.system_offsets[system + 1u];
  const std::int64_t qat_begin = g.layout.qat.system_offsets[system];
  const std::int64_t qat_end = g.layout.qat.system_offsets[system + 1u];
  const std::int64_t dip_begin = g.layout.dipole.system_offsets[system];
  const std::int64_t dip_end = g.layout.dipole.system_offsets[system + 1u];
  const std::int64_t quad_begin = g.layout.quadrupole.system_offsets[system];
  const std::int64_t quad_end = g.layout.quadrupole.system_offsets[system + 1u];
  return {
      std::vector<double>(g.wfn.qsh + shell_begin, g.wfn.qsh + shell_end),
      std::vector<double>(g.wfn.qat + qat_begin, g.wfn.qat + qat_end),
      std::vector<double>(g.wfn.dipole + dip_begin, g.wfn.dipole + dip_end),
      std::vector<double>(g.wfn.quadrupole + quad_begin, g.wfn.quadrupole + quad_end),
  };
}

xtbloom_status_t TraceBatch::build_geometry(std::string& err) {
  auto geometry = std::make_shared<Geometry>();
  Geometry& g = *geometry;
  g.batch_size = static_cast<std::int64_t>(specs_.size());
  if (g.batch_size <= 0) {
    err = "trace harness needs at least one case";
    return XTBLOOM_STATUS_INVALID_ARGUMENT;
  }

  std::int64_t total_atoms = 0;
  std::int64_t total_point_charges = 0;
  g.atom_offsets.assign(static_cast<std::size_t>(g.batch_size) + 1u, 0);
  g.pc_offsets.assign(static_cast<std::size_t>(g.batch_size) + 1u, 0);
  g.molecular_charges.resize(static_cast<std::size_t>(g.batch_size));
  g.unpaired.resize(static_cast<std::size_t>(g.batch_size));
  g.spins.resize(static_cast<std::size_t>(g.batch_size));
  for (std::int64_t system = 0; system < g.batch_size; ++system) {
    const CaseSpec& spec = specs_[static_cast<std::size_t>(system)];
    g.atom_offsets[static_cast<std::size_t>(system + 1)] =
        g.atom_offsets[static_cast<std::size_t>(system)] + spec.nat;
    g.pc_offsets[static_cast<std::size_t>(system + 1)] =
        g.pc_offsets[static_cast<std::size_t>(system)] +
        static_cast<std::int64_t>(spec.pc_rows.size() / 5u);
    g.molecular_charges[static_cast<std::size_t>(system)] = spec.molecular_charge;
    g.unpaired[static_cast<std::size_t>(system)] = spec.unpaired_electrons;
    g.spins[static_cast<std::size_t>(system)] = spec.spin_channels;
  }
  total_atoms = g.atom_offsets[static_cast<std::size_t>(g.batch_size)];
  total_point_charges = g.pc_offsets[static_cast<std::size_t>(g.batch_size)];

  g.positions.reserve(static_cast<std::size_t>(3 * total_atoms));
  for (const CaseSpec& spec : specs_) {
    g.positions.insert(g.positions.end(), spec.positions.begin(), spec.positions.end());
  }
  for (const CaseSpec& spec : specs_) {
    const std::int64_t npc = static_cast<std::int64_t>(spec.pc_rows.size() / 5u);
    for (std::int64_t ip = 0; ip < npc; ++ip) {
      const double* row = &spec.pc_rows[static_cast<std::size_t>(ip * 5)];
      g.pc_positions.insert(g.pc_positions.end(), {row[0], row[1], row[2]});
      g.pc_charges.push_back(row[3]);
      g.pc_hardnesses.push_back(row[4]);
    }
  }

  std::vector<std::int32_t> atomic_numbers;
  atomic_numbers.reserve(static_cast<std::size_t>(total_atoms));
  for (const CaseSpec& spec : specs_) {
    atomic_numbers.insert(atomic_numbers.end(), spec.atomic_numbers.begin(),
                          spec.atomic_numbers.end());
  }

  xtbloom_status_t s = make_basis_plan(g.batch_size, total_atoms, g.atom_offsets.data(),
                                       atomic_numbers.data(), g.basis, err);
  if (s) return s;
  s = make_integral_plan(g.basis, g.integrals, err);
  if (s) return s;
  s = make_h0_plan(g.basis, g.integrals, atomic_numbers.data(), g.h0_plan, err);
  if (s) return s;
  s = make_wavefunction_layout(g.basis, atomic_numbers.data(), g.molecular_charges.data(),
                               g.unpaired.data(), g.spins.data(), g.layout, err);
  if (s) return s;
  s = make_es2_plan(g.basis, atomic_numbers.data(), g.es2_plan, err);
  if (s) return s;
  s = make_es3_plan(g.basis, atomic_numbers.data(), g.es3_plan, err);
  if (s) return s;
  s = make_aes2_plan(g.basis, atomic_numbers.data(), g.aes2_plan, err);
  if (s) return s;
  s = make_mulliken_plan(g.basis, g.integrals, g.layout, g.mulliken_plan, err);
  if (s) return s;
  s = make_eigensolver_plan(g.layout, g.eig_plan, err);
  if (s) return s;
  s = make_coordination_plan(g.batch_size, total_atoms, g.atom_offsets.data(),
                             atomic_numbers.data(), g.coordination_plan, err);
  if (s) return s;
  if (total_point_charges > 0) {
    s = make_external_point_charge_plan(g.basis, atomic_numbers.data(), total_point_charges,
                                        g.pc_offsets.data(), g.pc_plan, err);
    if (s) return s;
  }
  s = make_d4_plan(g.batch_size, total_atoms, g.atom_offsets.data(), atomic_numbers.data(),
                   g.d4_plan, err);
  if (s) return s;

  const std::size_t matrix = static_cast<std::size_t>(g.integrals.total_matrix_elements);
  g.overlap.assign(matrix, 0.0);
  g.dint.assign(3 * matrix, 0.0);
  g.qint.assign(6 * matrix, 0.0);
  g.h0.assign(matrix, 0.0);
  g.cn.assign(static_cast<std::size_t>(total_atoms), 0.0);
  if (g.iscratch.size < g.integrals.workspace_size_bytes) return XTBLOOM_STATUS_ALLOCATION_FAILED;
  s = evaluate_coordination_cpu(g.coordination_plan, g.positions.data(), g.cn.data(), err);
  if (s) return s;
  s = evaluate_overlap_cpu(g.basis, g.integrals, g.positions.data(), g.overlap.data(),
                           g.iscratch.data, g.iscratch.size, err);
  if (s) return s;
  s = evaluate_multipole_cpu(g.basis, g.integrals, g.positions.data(), g.dint.data(), g.qint.data(),
                             g.iscratch.data, g.iscratch.size, err);
  if (s) return s;
  s = evaluate_h0_cpu(g.basis, g.integrals, g.h0_plan, g.positions.data(), g.cn.data(),
                      g.overlap.data(), g.h0.data(), err);
  if (s) return s;

  const std::size_t e2n = static_cast<std::size_t>(g.es2_plan.total_matrix_elements());
  if (g.e2s.size < e2n * sizeof(double)) return XTBLOOM_STATUS_ALLOCATION_FAILED;
  g.es2_ws.matrix_scratch = static_cast<double*>(g.e2scratch.data);
  g.es2_ws.matrix_elements = g.es2_plan.total_matrix_elements();
  s = update_es2_geometry_cache_cpu(g.es2_plan, g.positions.data(), 1u,
                                    static_cast<double*>(g.e2s.data), e2n, g.es2_ws, g.es2_cache,
                                    err);
  if (s) return s;

  const std::size_t a2n = static_cast<std::size_t>(g.aes2_plan.pair_data_elements());
  if (g.a2s.size < a2n * sizeof(double)) return XTBLOOM_STATUS_ALLOCATION_FAILED;
  g.aes2_ws.pair_scratch = static_cast<double*>(g.a2scratch.data);
  g.aes2_ws.pair_elements = g.aes2_plan.pair_data_elements();
  s = update_aes2_geometry_cache_cpu(g.aes2_plan, g.positions.data(), g.cn.data(), 1u,
                                     static_cast<double*>(g.a2s.data), a2n, g.aes2_ws, g.aes2_cache,
                                     err);
  if (s) return s;

  if (g.d4_buffer.size < g.d4_plan.workspace_size_bytes()) return XTBLOOM_STATUS_ALLOCATION_FAILED;
  s = bind_d4_workspace(g.d4_plan, g.d4_buffer.data, g.d4_buffer.size, g.d4_ws, err);
  if (s) return s;
  g.d4_pairs.assign(static_cast<std::size_t>(g.d4_plan.total_pairs()) * kD4PairDataElements, 0.0);
  g.d4_coordination.assign(static_cast<std::size_t>(g.d4_plan.total_atoms()), 0.0);
  s = update_d4_geometry_cache_cpu(g.d4_plan, g.positions.data(), 1u, g.d4_pairs.data(),
                                   g.d4_pairs.size(), g.d4_coordination.data(),
                                   g.d4_coordination.size(), g.d4_ws, g.d4_cache, err);
  if (s) return s;

  if (total_point_charges > 0) {
    g.pc_shell_potential.assign(static_cast<std::size_t>(g.basis.total_shells), 0.0);
    s = evaluate_external_point_charge_potential_cpu(
        g.pc_plan, g.positions.data(), g.pc_positions.data(), g.pc_charges.data(),
        g.pc_hardnesses.data(), g.pc_shell_potential.data(), err);
    if (s) return s;
  }

  g.geom.h0 = g.h0.data();
  g.geom.h0_elements = static_cast<std::int64_t>(g.h0.size());
  g.geom.integrals = {g.overlap.data(), g.dint.data(), g.qint.data(),
                      g.integrals.total_matrix_elements, g.mulliken_plan.identity()};
  g.geom.es2_cache = g.es2_cache;
  g.geom.aes2_cache = g.aes2_cache;
  g.geom.d4_cache = g.d4_cache;
  g.geom.geometry_generation = 1u;
  if (total_point_charges > 0) {
    g.geom.explicit_point_charge_shell_potential = g.pc_shell_potential.data();
    g.geom.explicit_point_charge_shell_elements =
        static_cast<std::int64_t>(g.pc_shell_potential.size());
  }

  s = make_mkl_rt_lp64_backend(g.backend, err);
  if (s) return s;
  if (g.wfn_s.size < g.layout.workspace_size_bytes) return XTBLOOM_STATUS_ALLOCATION_FAILED;
  s = bind_wavefunction_view(g.layout, g.wfn_s.data, g.wfn_s.size, g.wfn, err);
  if (s) return s;
  // Issue #49 closed-loop trajectories start from the same initial guess as
  // the pinned golden: tblite's new_wavefunction leaves the SCC perturbative
  // q/d/Q state at exactly zero.  The production SAD seed would otherwise move
  // the first mixed state (and for charged h3_plus the first ES2/ES3
  // potentials) away from the golden trajectory.
  s = initialize_sad_multipole_state(g.layout, g.wfn, err);
  if (s) return s;
  std::fill_n(g.wfn.qsh, static_cast<std::size_t>(g.layout.qsh.element_count), 0.0);
  std::fill_n(g.wfn.qat, static_cast<std::size_t>(g.layout.qat.element_count), 0.0);
  std::fill_n(g.wfn.dipole, static_cast<std::size_t>(g.layout.dipole.element_count), 0.0);
  std::fill_n(g.wfn.quadrupole, static_cast<std::size_t>(g.layout.quadrupole.element_count), 0.0);

  if (g.oc_s.size < g.eig_plan.overlap_cache_size_bytes()) return XTBLOOM_STATUS_ALLOCATION_FAILED;
  s = bind_eigensolver_overlap_cache(g.eig_plan, g.oc_s.data, g.oc_s.size, g.ocache, err);
  if (s) return s;
  if (g.eig_s.size < g.eig_plan.workspace_size_bytes()) return XTBLOOM_STATUS_ALLOCATION_FAILED;
  s = bind_eigensolver_workspace(g.eig_plan, g.eig_s.data, g.eig_s.size, g.eig_ws, err);
  if (s) return s;
  s = factor_overlap_cpu(g.eig_plan, g.overlap.data(), 1u, g.backend, g.eig_ws, g.ocache, err);
  if (s) return s;

  geometry_ = std::move(geometry);
  err.clear();
  return XTBLOOM_STATUS_SUCCESS;
}

xtbloom_status_t TraceBatch::build_stage(const CaseSpec& reference, std::string& err) {
  Geometry& g = *geometry_;
  auto stage = std::make_shared<Stage>();
  xtbloom_status_t s =
      make_scc_mixer_plan(g.layout, reference.mixer_memory, reference.mixer_damping,
                          kTbliteRmsTolerance, kTbliteRmsTolerance, stage->mixer_plan, err);
  if (s) return s;
  // Honor the case-spec maximum-iteration cap exactly so a deliberately
  // nonconverged or capped trace reaches the same terminal state as the
  // oracle instead of silently continuing to the harness safety ceiling.
  s = make_scc_driver_plan(g.layout, g.mulliken_plan, g.es2_plan, g.es3_plan, g.aes2_plan,
                           g.eig_plan, stage->mixer_plan, &g.d4_plan, nullptr,
                           static_cast<std::uint64_t>(reference.maximum_iterations),
                           reference.temperature_kelvin * kKelvinToHartree, kTbliteEnergyTolerance,
                           stage->driver_plan, err);
  if (s) return s;
  if (stage->mixer_s.size < stage->mixer_plan.state_size_bytes()) {
    return XTBLOOM_STATUS_ALLOCATION_FAILED;
  }
  s = bind_scc_mixer_state(stage->mixer_plan, stage->mixer_s.data, stage->mixer_s.size,
                           stage->mixer_state, err);
  if (s) return s;
  if (stage->drv_s.size < stage->driver_plan.state_size_bytes()) {
    return XTBLOOM_STATUS_ALLOCATION_FAILED;
  }
  s = bind_scc_driver_state(stage->driver_plan, stage->drv_s.data, stage->drv_s.size,
                            stage->driver_state, err);
  if (s) return s;
  if (stage->drvws_s.size < stage->driver_plan.workspace_size_bytes()) {
    return XTBLOOM_STATUS_ALLOCATION_FAILED;
  }
  s = bind_scc_driver_workspace(stage->driver_plan, stage->drvws_s.data, stage->drvws_s.size,
                                stage->drv_ws, err);
  if (s) return s;
  s = initialize_scc_driver_state_cpu(stage->driver_plan, g.wfn, stage->mixer_state,
                                      stage->driver_state, err);
  if (s) return s;
  stage_ = std::move(stage);
  iterations_.assign(static_cast<std::size_t>(g.batch_size), {});
  failed_attempts_.assign(static_cast<std::size_t>(g.batch_size), {});
  err.clear();
  return XTBLOOM_STATUS_SUCCESS;
}

xtbloom_status_t TraceBatch::build(std::string& err) {
  xtbloom_status_t s = validate_policy_homogeneity(err);
  if (s != XTBLOOM_STATUS_SUCCESS) {
    return s;
  }
  s = build_geometry(err);
  if (s) return s;
  return build_stage(specs_.front(), err);
}

xtbloom_status_t TraceBatch::validate_policy_homogeneity(std::string& err) const {
  if (specs_.empty()) {
    err = "trace harness needs at least one case";
    return XTBLOOM_STATUS_INVALID_ARGUMENT;
  }
  const CaseSpec& reference = specs_.front();
  for (std::size_t index = 1u; index < specs_.size(); ++index) {
    const CaseSpec& candidate = specs_[index];
    const bool same_policy = candidate.mixer_memory == reference.mixer_memory &&
                             candidate.mixer_damping == reference.mixer_damping &&
                             candidate.maximum_iterations == reference.maximum_iterations &&
                             candidate.temperature_kelvin == reference.temperature_kelvin;
    if (!same_policy) {
      err =
          "ragged batch cases must share one numerical policy (temperature, "
          "mixer memory/damping, maximum iterations); lane " +
          std::to_string(index) + " differs";
      return XTBLOOM_STATUS_INVALID_ARGUMENT;
    }
  }
  err.clear();
  return XTBLOOM_STATUS_SUCCESS;
}

void TraceBatch::poison_h0(std::int64_t system) {
  Geometry& g = *geometry_;
  const std::int64_t matrix_begin = g.mulliken_plan.matrix_offsets()[system];
  const std::int64_t matrix_end = g.mulliken_plan.matrix_offsets()[system + 1u];
  for (std::int64_t element = matrix_begin; element < matrix_end; ++element) {
    g.h0[static_cast<std::size_t>(element)] = std::numeric_limits<double>::quiet_NaN();
  }
}

void TraceBatch::poison_eigensolver(std::int64_t system) {
  geometry_->ocache.system_statuses[system] = XTBLOOM_STATUS_EIGENSOLVER_FAILED;
}

xtbloom_status_t TraceBatch::inject_mixed_state(std::int64_t system, const std::string& state_path,
                                                std::string& err) {
  Geometry& g = *geometry_;
  const std::int64_t shell_begin = g.layout.qsh.system_offsets[system];
  const std::int64_t shell_end = g.layout.qsh.system_offsets[system + 1u];
  const std::int64_t qat_begin = g.layout.qat.system_offsets[system];
  const std::int64_t qat_end = g.layout.qat.system_offsets[system + 1u];
  const std::int64_t dip_base = g.layout.dipole.system_offsets[system];
  const std::int64_t quad_base = g.layout.quadrupole.system_offsets[system];
  const std::int64_t shells = shell_end - shell_begin;
  const std::int64_t atoms = qat_end - qat_begin;

  std::ifstream file(state_path);
  if (!file) {
    err = "cannot open state file " + state_path;
    return XTBLOOM_STATUS_INVALID_ARGUMENT;
  }
  double value = 0.0;
  std::int64_t count = 0;

  auto read_section = [&](const char* label, std::int64_t expected) -> bool {
    std::string token;
    if (!(file >> token) || token != label) {
      err = std::string("state file missing section ") + label;
      return false;
    }
    if (!(file >> count) || count != expected) {
      err = std::string("state file ") + label + " has wrong count";
      return false;
    }
    return true;
  };
  if (!read_section("qsh", shells)) return XTBLOOM_STATUS_INVALID_ARGUMENT;
  for (std::int64_t local = 0; local < shells; ++local) {
    if (!(file >> value) || !std::isfinite(value)) {
      err = "state file qsh value malformed";
      return XTBLOOM_STATUS_INVALID_ARGUMENT;
    }
    g.wfn.qsh[shell_begin + local] = value;
  }
  if (!read_section("qat", atoms)) return XTBLOOM_STATUS_INVALID_ARGUMENT;
  for (std::int64_t local = 0; local < atoms; ++local) {
    if (!(file >> value) || !std::isfinite(value)) {
      err = "state file qat value malformed";
      return XTBLOOM_STATUS_INVALID_ARGUMENT;
    }
    g.wfn.qat[qat_begin + local] = value;
  }
  if (!read_section("dipoles", 3 * atoms)) return XTBLOOM_STATUS_INVALID_ARGUMENT;
  for (std::int64_t local = 0; local < 3 * atoms; ++local) {
    if (!(file >> value) || !std::isfinite(value)) {
      err = "state file dipole value malformed";
      return XTBLOOM_STATUS_INVALID_ARGUMENT;
    }
    g.wfn.dipole[dip_base + local] = value;
  }
  if (!read_section("quadrupoles", 6 * atoms)) return XTBLOOM_STATUS_INVALID_ARGUMENT;
  for (std::int64_t local = 0; local < 6 * atoms; ++local) {
    if (!(file >> value) || !std::isfinite(value)) {
      err = "state file quadrupole value malformed";
      return XTBLOOM_STATUS_INVALID_ARGUMENT;
    }
    g.wfn.quadrupole[quad_base + local] = value;
  }
  err.clear();
  return XTBLOOM_STATUS_SUCCESS;
}

void TraceBatch::set_replay_context(std::int64_t system, std::uint64_t logical_index,
                                    double previous_energy) {
  // The driver computes the energy change as (new - old) where old is
  // state.free_energies once iterations > 0.  Seeding the logical iteration
  // and previous internal energy reproduces tblite's energy_delta and
  // econverged flag for golden iteration logical_index.
  if (logical_index > 1u) {
    stage_->driver_state.iterations[system] = logical_index - 1u;
    stage_->driver_state.free_energies[system] = previous_energy;
  }
}

xtbloom_status_t TraceBatch::step(std::string& err) {
  return iterate_scc_driver_batch_cpu(stage_->driver_plan, geometry_->geom, geometry_->backend,
                                      geometry_->ocache, geometry_->wfn, stage_->mixer_state,
                                      stage_->driver_state, stage_->drv_ws, err);
}

xtbloom_status_t TraceBatch::step_once(std::string& err) {
  capture_mixed_pre_step();
  const xtbloom_status_t status = step(err);
  if (status != XTBLOOM_STATUS_SUCCESS && status != XTBLOOM_STATUS_SCC_NOT_CONVERGED &&
      status != XTBLOOM_STATUS_EIGENSOLVER_FAILED && status != XTBLOOM_STATUS_INTERNAL_ERROR) {
    return status;
  }
  record_iteration_snapshots();
  return XTBLOOM_STATUS_SUCCESS;
}

