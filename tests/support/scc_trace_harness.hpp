inline constexpr double kKelvinToHartree = 3.166808578545117e-6;
// Match tblite's singlepoint convergence policy exactly: with accuracy=1.0
// the electronic energy gate is econv = 1.0e-6*accuracy and the population
// gate is pconv = 2.0e-5*accuracy.  The goldens were generated by that pinned
// policy, so closed-loop and replay comparisons are only meaningful when the
// CPU driver uses the same thresholds.
inline constexpr double kTbliteEnergyTolerance = 1.0e-6;
inline constexpr double kTbliteRmsTolerance = 2.0e-5;
// Iterations never legitimately reach this many for the pinned corpus.
inline constexpr std::uint64_t kMaximumHarnessIterations = 256u;

struct AlignedBuffer {
  void* data = nullptr;
  std::size_t size = 0u;
  explicit AlignedBuffer(std::size_t requested) {
    size = (std::max<std::size_t>(requested, 1u) + 63u) & ~std::size_t{63u};
    data = std::aligned_alloc(64u, size);
    if (data != nullptr) {
      std::memset(data, 0, size);
    }
  }
  ~AlignedBuffer() { std::free(data); }
  AlignedBuffer(const AlignedBuffer&) = delete;
  AlignedBuffer& operator=(const AlignedBuffer&) = delete;
};

struct CaseSpec {
  std::int64_t nat = 0;
  std::vector<std::int32_t> atomic_numbers;
  std::vector<double> positions;
  double molecular_charge = 0.0;
  std::int32_t unpaired_electrons = 0;
  std::int32_t spin_channels = 1;
  double temperature_kelvin = 300.0;
  std::int64_t mixer_memory = 2;
  double mixer_damping = 0.4;
  std::int64_t maximum_iterations = 100;
  std::vector<double> pc_rows;  // x y z q gamma per point charge
};

inline bool load_spec(const std::string& path, CaseSpec& spec, std::string& err) {
  std::ifstream file(path);
  if (!file) {
    err = "cannot open spec " + path;
    return false;
  }
  if (!(file >> spec.nat)) {
    err = "missing atom count";
    return false;
  }
  spec.atomic_numbers.resize(static_cast<std::size_t>(spec.nat));
  for (auto& number : spec.atomic_numbers) {
    if (!(file >> number)) {
      err = "missing atomic number";
      return false;
    }
  }
  spec.positions.resize(static_cast<std::size_t>(spec.nat * 3));
  for (auto& value : spec.positions) {
    if (!(file >> value)) {
      err = "missing position";
      return false;
    }
  }
  if (!(file >> spec.molecular_charge)) {
    err = "missing charge";
    return false;
  }
  if (!(file >> spec.unpaired_electrons)) {
    err = "missing unpaired electrons";
    return false;
  }
  if (!(file >> spec.temperature_kelvin)) {
    err = "missing temperature";
    return false;
  }
  if (!(file >> spec.mixer_memory)) {
    err = "missing mixer memory";
    return false;
  }
  if (!(file >> spec.mixer_damping)) {
    err = "missing mixer damping";
    return false;
  }
  if (!(file >> spec.maximum_iterations)) {
    err = "missing max iterations";
    return false;
  }
  std::int64_t npc = 0;
  if (!(file >> npc)) {
    err = "missing point-charge count";
    return false;
  }
  spec.pc_rows.resize(static_cast<std::size_t>(npc * 5));
  for (auto& value : spec.pc_rows) {
    if (!(file >> value)) {
      err = "missing point-charge value";
      return false;
    }
  }
  // v2 specs append an explicit spin-channel selector.  EOF here is the
  // backward-compatible v1 representation and therefore means restricted.
  std::int32_t spin_channels = 1;
  if (file >> spin_channels) {
    if (spin_channels != 1 && spin_channels != 2) {
      err = "spin channels must be one or two";
      return false;
    }
    spec.spin_channels = spin_channels;
  } else if (!file.eof()) {
    err = "malformed optional spin-channel selector";
    return false;
  }
  return true;
}

// One captured iteration in the raw stream section order.  The logical index
// matches the golden's iterations[i].index.
struct CapturedIteration {
  // Production stores the Hamiltonian passed to the solver.  v2 additionally
  // emits the tblite assembled representation as exactly one half of it.
  std::vector<double> hamiltonian, eigenvalues, occupations_alpha, occupations_beta, density;
  std::vector<double> mixed_qsh, mixed_qat, mixed_dipoles, mixed_quadrupoles;
  std::vector<double> raw_qsh, raw_qat, raw_dipoles, raw_quadrupoles;
  std::vector<double> point_charge_shell_potential, point_charge_energy;
  double energy = 0.0;
  double energy_delta = 0.0;
  double residual_rms = 0.0;
  int econv = 0;
  int pconv = 0;
  int tconv = 1;
  int conv = 0;
};

// A solve attempt that reached the assembled Hamiltonian but failed before
// producing a valid eigensolution.  The v1 trace contract deliberately keeps
// only this pre-solve state so stale post-solve workspace cannot masquerade as
// a completed iteration.
struct CapturedFailedAttempt {
  bool present = false;
  std::vector<double> hamiltonian;
  std::vector<double> mixed_qsh, mixed_qat, mixed_dipoles, mixed_quadrupoles;
};

/*
 * One ragged batch of corpus cases driven as a single GFN2 SCC driver plan.
 *
 * add_case() fills the batch, build() creates every plan/cache and seeds the
 * zero-charge state, then step()/run() advance the systems and emit() writes
 * each lane's raw recorder stream.  poison_h0() marks one lane as a controlled
 * per-system preparation failure, and inject_mixed_state() +
 * set_replay_context() seed one lane from a golden mixed state for the
 * single-iteration replay (issue #49).
 */
class TraceBatch {
 public:
  TraceBatch() = default;
  TraceBatch(const TraceBatch&) = delete;
  TraceBatch& operator=(const TraceBatch&) = delete;

  std::int64_t system_count() const noexcept { return static_cast<std::int64_t>(specs_.size()); }
  const CaseSpec& spec(std::int64_t index) const { return specs_[static_cast<std::size_t>(index)]; }

  xtbloom_status_t system_status(std::int64_t index) const;
  std::uint64_t system_iterations(std::int64_t index) const;
  bool system_converged(std::int64_t index) const;
  // Live per-system multipole slice {qsh, qat, dipoles, quadrupoles}, for
  // native tests that verify output placement and early-convergence freezing.
  std::vector<std::vector<double>> live_state(std::int64_t system) const;
  const std::vector<CapturedIteration>& iterations(std::int64_t index) const {
    return iterations_[static_cast<std::size_t>(index)];
  }

  void add_case(const CaseSpec& spec) { specs_.push_back(spec); }

  // Every lane in one driver plan shares one numerical policy (temperature,
  // mixer memory/damping, and the maximum-iteration cap).  Emitting a lane
  // whose spec declares a different policy than the one the plan actually ran
  // would be dishonest trace evidence, so reject such batches at build time.
  xtbloom_status_t validate_policy_homogeneity(std::string& err) const;

  xtbloom_status_t build(std::string& err);
  // Write NaN into the H0 slice of one system so its next preparation phase
  // fails per-system without touching peers (controlled failure-isolation
  // member for issue #50).  Must be called after build() and before run().
  void poison_h0(std::int64_t system);
  // Mark one lane's overlap cache unusable so its next active attempt reaches
  // Hamiltonian assembly and then fails specifically in the eigensolver.  This
  // is a test-only injection seam for the trace failed_attempt lifecycle.
  void poison_eigensolver(std::int64_t system);
  // Inject the golden mixed q/d/Q state into one system before the first
  // step() (single-iteration replay for issue #49).  The state file layout is
  // line-oriented: "qsh <n>" then n values, "qat <n>" then n values,
  // "dipoles <n>" then n values, "quadrupoles <n>" then n values.
  xtbloom_status_t inject_mixed_state(std::int64_t system, const std::string& state_path,
                                      std::string& err);
  // Choose the injected state's logical iteration number and previous internal
  // energy so a replay of golden iteration k computes the same energy_delta
  // and convergence flags as tblite.
  void set_replay_context(std::int64_t system, std::uint64_t logical_index, double previous_energy);
  // Re-capture one system's mixer current input from the injected wavefunction
  // state and clear its history, so a single-iteration replay's residual is
  // raw minus the injected golden mixed state (not the zero init).
  xtbloom_status_t restart_mixer_system(std::int64_t system, std::string& err);
  // Overwrite one system's multipole state from flattened vectors in the
  // canonical residual order (qsh, then atom-major dipoles, then atom-major
  // quadrupoles).  Used by the independent golden-residual mixer replay.
  xtbloom_status_t write_multipoles(std::int64_t system, const std::vector<double>& qsh,
                                    const std::vector<double>& dpat,
                                    const std::vector<double>& qpat, std::string& err);
  // Run one production Broyden mixer transition for one system against its
  // current wavefunction raw multipoles and mixer current input.  After a
  // successful call the wavefunction multipoles hold the next mixed input.
  xtbloom_status_t mixer_mix(std::int64_t system, std::string& err);
  // Return the wavefunction multipoles flattened in the residual order after
  // a mixer transition (the next mixed input).
  std::vector<double> next_mixed_flattened(std::int64_t system) const;
  // Advance every active system by exactly one driver iteration.  Successful
  // peers are committed even when another lane failed.
  xtbloom_status_t step(std::string& err);
  // One full harness iteration: capture pre-solve mixed state, advance every
  // active system by one driver iteration, and record the per-lane snapshots.
  xtbloom_status_t step_once(std::string& err);
  // Loop step() until every system is terminal or kMaximumHarnessIterations
  // passes.  A per-lane failure (for example the poisoned lane) does not
  // suppress the successful lanes.
  xtbloom_status_t run(std::string& err);
  // Append the complete raw stream of one system in the recorder layout.
  void emit(std::ostream& output, std::int64_t system) const;

 private:
  struct Geometry;
  struct Stage;

  xtbloom_status_t build_geometry(std::string& err);
  xtbloom_status_t build_stage(const CaseSpec& reference, std::string& err);
  // Capture the pre-solve mixed q/d/Q of every active lane before a step.
  void capture_mixed_pre_step();
  // Append one CapturedIteration for every lane that advanced this call,
  // pairing each raw/energy/convergence payload with the pre-solve mixed
  // state captured by capture_mixed_pre_step().
  void record_iteration_snapshots();

  std::vector<CaseSpec> specs_;
  std::shared_ptr<Geometry> geometry_;
  std::shared_ptr<Stage> stage_;
  std::vector<std::vector<CapturedIteration>> iterations_;
  std::vector<CapturedFailedAttempt> failed_attempts_;
  // Pre-solve mixed state per lane: {qsh, qat, dipoles, quadrupoles}.
  std::vector<std::vector<std::vector<double>>> pending_mixed_;
};

