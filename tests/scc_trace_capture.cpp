// gpuxtb CPU SCC trace capture for the pinned tblite corpus (issues #49/#50).
//
// Reads a corpus case.spec (the same fixed layout emitted by
// generate_scc_corpus.py), runs the production CPU GFN2 SCC driver one
// iteration at a time, and streams the captured per-iteration state in exactly
// the same raw layout as the Fortran tblite recorder so that
// generate_scc_corpus.canonicalize() can assemble a gpuxtb-scc-trace-v1
// document and the comparator can compare it against the pinned golden.
//
// This executable is test-only tooling against internal GFN2 headers; it is
// not part of the public C ABI.
